import { jsPDF } from "jspdf";

import { structureQuestionAnswerMarkdown } from "@/lib/format-worksheet-markdown";
import { buildLessonPlanSupplement } from "@/lib/lesson-plan-supplement";
import {
  PDF_INK,
  PDF_MUTED,
  PDF_RULE,
  PdfWriter,
} from "@/services/pdf-writer";

export type LessonPlanPdfInput = {
  topic: string;
  curriculumRoute: string;
  grade: string;
  subject: string;
  content: string;
  /** Cover metadata — omitted values print as "-" (Flutter parity). */
  schoolName?: string | null;
  preparedBy?: string | null;
  teachingStrategy?: string | null;
  duration?: string | null;
};

const MARGIN = 48;
/** Leaves room for the "Generated by Make My Lesson" strip on every page. */
const CONTENT_TOP = MARGIN + 22;

function safeFilename(topic: string): string {
  const safe = topic.trim().replace(/[^a-zA-Z0-9]+/g, "_") || "lesson";
  return `lesson_plan_${safe}_${Date.now()}.pdf`;
}

function dash(value: string | null | undefined): string {
  return (value ?? "").trim() || "-";
}

function formatToday(): string {
  return new Date().toLocaleDateString("en-US", {
    year: "numeric",
    month: "long",
    day: "numeric",
  });
}

function drawCover(w: PdfWriter, input: LessonPlanPdfInput): void {
  const { doc } = w;

  doc.setFont("helvetica", "bold");
  doc.setFontSize(9);
  doc.setTextColor(PDF_MUTED);
  doc.text("LESSON PLAN", MARGIN, w.y);
  w.gap(20);

  doc.setFontSize(20);
  doc.setTextColor(PDF_INK);
  for (const line of doc.splitTextToSize(
    input.topic.trim() || "Lesson Plan",
    w.maxWidth,
  ) as string[]) {
    w.ensure(24);
    doc.text(line, MARGIN, w.y);
    w.gap(24);
  }
  w.gap(10);

  const meta: [string, string][] = [
    ["SCHOOL", dash(input.schoolName)],
    ["PREPARED BY", dash(input.preparedBy)],
    ["SUBJECT", dash(input.subject)],
    ["GRADE / YEAR", dash(input.grade)],
    ["CURRICULUM", dash(input.curriculumRoute)],
    ["TEACHING STRATEGY", dash(input.teachingStrategy)],
    ["DURATION", dash(input.duration)],
    ["DATE", formatToday()],
  ];

  const colWidth = w.maxWidth / 2;
  for (let i = 0; i < meta.length; i += 2) {
    const cells = meta.slice(i, i + 2).map(([label, value]) => {
      doc.setFont("helvetica", "normal");
      doc.setFontSize(10);
      return {
        label,
        lines: doc.splitTextToSize(value, colWidth - 12) as string[],
      };
    });
    const rowHeight =
      11 + Math.max(...cells.map((c) => c.lines.length)) * 13 + 10;
    w.ensure(rowHeight);
    const rowTop = w.y;
    cells.forEach((cell, col) => {
      const x = MARGIN + col * colWidth;
      doc.setFont("helvetica", "bold");
      doc.setFontSize(7.5);
      doc.setTextColor(PDF_MUTED);
      doc.text(cell.label, x, rowTop);
      doc.setFont("helvetica", "normal");
      doc.setFontSize(10);
      doc.setTextColor(PDF_INK);
      cell.lines.forEach((line, li) => {
        doc.text(line, x, rowTop + 12 + li * 13);
      });
    });
    w.y = rowTop + rowHeight;
  }

  w.gap(6);
  w.rule();
  w.gap(20);
}

function drawSupplement(w: PdfWriter, input: LessonPlanPdfInput): void {
  const supplement = buildLessonPlanSupplement({
    curriculumRoute: input.curriculumRoute,
    grade: input.grade,
    subject: input.subject,
  });

  // These blocks are short and fixed, so keep each one whole on a single page.
  w.heading(supplement.successCriteria.heading, 2, {
    ruled: true,
    keepWith: supplement.successCriteria.items.length * 17,
  });
  for (const item of supplement.successCriteria.items) w.checkbox(item);

  w.heading(supplement.curriculumAlignment.heading, 2, {
    ruled: true,
    keepWith: 60,
  });
  w.paragraph(supplement.curriculumAlignment.body);

  w.heading(supplement.learningResources.heading, 2, {
    ruled: true,
    keepWith: supplement.learningResources.items.length * 16,
  });
  for (const item of supplement.learningResources.items) w.bullet(item);

  w.heading(supplement.rubric.heading, 2, {
    ruled: true,
    keepWith: 24 + (supplement.rubric.rows.length + 1) * 24,
  });
  w.paragraph(supplement.rubric.note, {
    size: 9.5,
    color: PDF_MUTED,
    italic: true,
    after: 8,
  });
  w.table({
    columns: supplement.rubric.columns,
    rows: supplement.rubric.rows,
    weights: [0.28, 0.24, 0.24, 0.24],
    firstColumnBold: true,
  });

  w.heading(supplement.teacherReflection.heading, 2, {
    ruled: true,
    keepWith: 24 + 2 * 47,
  });
  w.paragraph(supplement.teacherReflection.note, {
    size: 9.5,
    color: PDF_MUTED,
    italic: true,
    after: 6,
  });
  for (const question of supplement.teacherReflection.questions) {
    w.ensure(34);
    w.paragraph(question, { size: 10.5, bold: true, after: 0 });
    w.answerLine();
  }
}

/** "Generated by Make My Lesson" + page numbers, added once totals are known. */
function stampPageHeaders(doc: jsPDF, pageWidth: number): void {
  const total = doc.getNumberOfPages();
  for (let page = 1; page <= total; page += 1) {
    doc.setPage(page);
    doc.setFont("helvetica", "normal");
    doc.setFontSize(8);
    doc.setTextColor(PDF_MUTED);
    doc.text("Generated by Make My Lesson", MARGIN, MARGIN - 14);
    doc.text(`Page ${page} of ${total}`, pageWidth - MARGIN, MARGIN - 14, {
      align: "right",
    });
    doc.setDrawColor(PDF_RULE);
    doc.line(MARGIN, MARGIN - 8, pageWidth - MARGIN, MARGIN - 8);
  }
}

export function buildLessonPlanPdf(input: LessonPlanPdfInput): jsPDF {
  const doc = new jsPDF({ unit: "pt", format: "a4" });
  const writer = new PdfWriter(doc, {
    margin: MARGIN,
    contentTop: CONTENT_TOP,
  });

  drawCover(writer, input);
  writer.markdown(structureQuestionAnswerMarkdown(input.content));
  drawSupplement(writer, input);
  stampPageHeaders(doc, writer.pageWidth);

  return doc;
}

export function downloadLessonPlanPdf(input: LessonPlanPdfInput): void {
  const doc = buildLessonPlanPdf(input);
  doc.save(safeFilename(input.topic));
}

export function printLessonPlanPdf(input: LessonPlanPdfInput): void {
  const doc = buildLessonPlanPdf(input);
  doc.autoPrint();
  const blobUrl = doc.output("bloburl");
  window.open(blobUrl, "_blank");
}

export async function shareLessonPlanPdf(input: LessonPlanPdfInput) {
  const { shareBlobFile } = await import("@/services/document-export-core");
  const doc = buildLessonPlanPdf(input);
  const blob = doc.output("blob");
  return shareBlobFile({
    blob,
    filename: safeFilename(input.topic),
    title: `Stage 1 — ${input.topic}`,
    text: `Lesson plan for ${input.topic}`,
  });
}
